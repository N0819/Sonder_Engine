def run_once(chat_id, char_id, name, walls, *, agent, max_steps, turn_base,
             verbose, rng=None, show_grid=False, optimal_path=(),
             collect_trace=False, think_path=None, run_no=0,
             resume_from=0, resume_visited=None, checkpoint=None):
    """One traversal. Returns the ordered list of rooms occupied."""
    from core import db as _db
    from core.db import qi, wget, wset
    from core.pipeline_context import PipelineContext, ChatData, TurnData
    from story.scene import active_cast
    import agents.runtime as runtime

    # On resume the position is already in the DB -- it is where he stopped,
    # not the start -- so the route is restored rather than begun.
    visited = list(resume_visited or []) or [position_of(chat_id, name)]
    stalls = []
    trace = [] if collect_trace else None
    for step in range(resume_from, max_steps):
        # Taken from the DB rather than counted in this process. `turn_base +=
        # len(visited)` undercounted: a STALLED beat inserts its turn row and
        # then skips the append, so every stall left the next run starting one
        # index low and eventually colliding on (chat_id, idx). It never bit
        # while the character model did not stall, which is exactly the kind
        # of bug that waits for the one arm you care about. One small query a
        # beat is nothing beside the LLM calls, and it cannot be miscounted.
        _max = _db.q("SELECT MAX(idx) AS m FROM turns WHERE chat_id=?",
                     (chat_id,), one=True)
        idx = int((_max or {})["m"] or 0) + 1
        turn_id = qi(
            "INSERT INTO turns(chat_id,idx,player_input,created) VALUES(?,?,?,?)",
            (chat_id, idx, "", time.time()))
        row = _db.q("SELECT * FROM chats WHERE id=?", (chat_id,), one=True)
        ctx = PipelineContext(
            chat=ChatData(id=chat_id, name=row["name"], persona_id=row["persona_id"],
                          lorebook_id=row["lorebook_id"], scenario=row["scenario"],
                          created=row["created"]),
            turn=TurnData(id=turn_id, chat_id=chat_id, idx=idx,
                          player_input="", created=time.time()),
            cast=active_cast(chat_id),
            input="",
        )
        # No player this beat: the sequence is empty and flow asks for nothing.
        # `reactors` is load-bearing, not boilerplate: perception_act builds a
        # perceiver ONLY for a character listed here, so an empty list meant
        # the character was never a perceiver and character_step fell through
        # to "You register nothing new this beat." on every beat. In real play
        # director_interpret populates this from the player's act; with no
        # player, the character is the only mind in the scene and always
        # perceives.
        ctx["director_interpret"] = {
            "sequence": [],
            "flow": {"needs_mapping": False, "reactors": [char_id],
                     "resolution_flags": {}},
            "authorial_offers": [],
        }

        if agent in ("random",):
            result = _random_agent_handler(walls, name, rng)(ctx, char_id, 0)
            ctx[f"character:{char_id}"] = result
            # The control does not exercise the director; move it directly so
            # the baseline measures NAVIGATION, not the resolver.
            sc = wget(chat_id, "scene", {}) or {}
            sc.setdefault("positions", {})[name] = result["_forced_move"]
            wset(chat_id, "scene", sc)
        else:
            _scripted_here[0] = position_of(chat_id, name)
            # A model that returns a slightly-off shape raises out of
            # complete_validated_json and would otherwise end a multi-hour
            # unattended run at whatever step it happened on. Retry the beat
            # once, then skip it: a skipped beat is a stalled character, which
            # the metrics already record honestly as a step with no move.
            try:
                for key in _PRE_CHARACTER:
                    ctx[key] = runtime.compute_step(key, ctx, 0)
                ctx[f"character:{char_id}"] = runtime.compute_step(
                    f"character:{char_id}", ctx, 0)
                # Grabbed HERE, not at the end of the beat. The ContextVar
                # holds whichever call set it last, and the four stages below
                # are all mercury -- which returns no reasoning, so it
                # overwrites the character's with nothing. Read at dump time
                # it was always empty, which looked like the model not
                # exposing a trace rather than us reading the wrong moment.
                try:
                    from llm.providers import last_reasoning as _lr
                    char_reasoning = str(_lr.get() or "")
                except Exception:
                    char_reasoning = ""
                for key in _LLM_CHAIN:
                    ctx[key] = runtime.compute_step(key, ctx, 0)
            except Exception as exc:
                stalls.append(f"step {step + 1}: {type(exc).__name__}: {exc}")
                print(f"    step {step + 1:3}  STALLED "
                      f"({type(exc).__name__}: {str(exc)[:120]})", flush=True)
                # A stall the run cannot recover from must END it, not be
                # retried sixty times. Out of credit, a revoked key or a dead
                # provider fails INSTANTLY, so the beat loop stops being rate
                # limited by the network and spins at full speed: observed
                # live, an exhausted OpenRouter balance turned into 272
                # identical stalls in seconds, burying 26 real beats of
                # results under them and reporting a stall count that looked
                # like a model problem.
                #
                # Matched against the PROVIDER's half of the message only.
                # llm_quality appends `| model sent: <raw>` and the model's
                # own reasoning to a validation error, so a bare substring
                # test searched the MODEL's output for HTTP codes -- and this
                # maze contains Chamber 0403. One ordinary schema failure
                # killed a five-run arm at run 2 beat 32 and reported it as
                # the provider being unable to serve the run. Three-digit
                # codes need a digit boundary for the same reason: 402 must
                # not match r0402.
                _provider_part = re.split(r"\| (?:model sent|reasoning):",
                                          str(exc))[0]
                _fatal = (re.search(r"(?<!\d)(40[123])(?!\d)", _provider_part)
                          or any(sig in _provider_part for sig in
                                 ("Insufficient credits",
                                  "No usable model configured")))
                # Dumped BEFORE deciding whether to abort. A stalled beat is
                # the one worth reading -- it is where a model's output and
                # the schema disagreed -- and aborting is when that matters
                # most, yet it was the one path that threw the evidence away.
                # What exists at this point is exactly what the failing stage
                # was handed.
                if think_path:
                    _dump_thoughts(
                        think_path, run_no, step + 1, visited[-1],
                        ctx.get(f"character:{char_id}") or {},
                        ctx.get("director_resolve") or {},
                        stalled=f"{type(exc).__name__}: {exc}",
                        reasoning=locals().get("char_reasoning", ""))
                if _fatal:
                    print(f"    ABORTING RUN -- unrecoverable: "
                          f"{str(exc)[:160]}", flush=True)
                    raise SystemExit(
                        "maze: aborting, the provider cannot serve this run "
                        f"({str(exc)[:200]}). Completed beats and the "
                        "checkpoint are intact -- fix the cause and --resume.")
                continue

        if agent != "random":
            _out = ctx.get(f"character:{char_id}") or {}
            _res = ctx.get("director_resolve") or {}
            if think_path:
                _dump_thoughts(think_path, run_no, step + 1, visited[-1],
                               _out, _res, reasoning=char_reasoning)
            if trace is not None:
                trace.append({
                    "beat": step + 1,
                    "from": visited[-1],
                    "private_thought": str(_out.get("private_thought") or "")[:300],
                    "declared": [
                        {"type": e.get("type"), "verb": e.get("verb"),
                         "attempt": str(e.get("attempt") or e.get("text") or "")[:200]}
                        for e in (_out.get("sequence") or []) if isinstance(e, dict)],
                    "resolved": str(_res.get("summary") or "")[:200],
                    # The view the character actually navigated on: a
                    # perception model can return schema-valid output too thin
                    # to recognise a room from, which surfaces as worse
                    # navigation rather than as an error.
                    "view": {
                        k: str(v)[:400] for k, v in
                        ((ctx.get("perception_outcome") or {}).get("views")
                         or {}).items()},
                })

        here = position_of(chat_id, name)
        visited.append(here)
        if verbose:
            print(f"    step {step + 1:3}  {here}")
        if show_grid:
            print(render_grid(walls, here, visited, optimal_path))
            print(f"    step {step + 1} | at {here} | "
                  f"{len(set(visited))} of {GRID * GRID} chambers seen",
                  flush=True)
        if checkpoint:
            # After every beat, because the whole point is that a run
            # interrupted to fix code loses at most the beat in flight. The
            # DB already holds everything the character IS -- memory, mind
            # models, chat_chars.state, his position -- so what has to be
            # written here is only what lives in this process: which run and
            # beat, the route so far, and the rng.
            checkpoint(run_no, step + 1, visited)
        if here == _rid(GOAL):
            reward_on_contact(chat_id, char_id, name)
            break
    if stalls:
        print(f"    ({len(stalls)} stalled beats this run)")
    return visited, (trace or [])


def reward_on_contact(chat_id, char_id, name):
    """The shrine itself is the reward, felt where it is, the beat he touches
    it.

    This should have been the shape from the start. The interlude fed him at
    the run BOUNDARY, so the hedonic charge and the memory both landed after
    the fact and attached to the meal: measured after his first arrival,
    `pleasure 0.45, source "hot barley and dark beer after the run"`, and not
    one belief anywhere in his state mentioning the shrine. He walked
    forty-eight moves to the object of the entire experiment and what
    registered was dinner.

    That is why the scenery kept winning. A shattered mirror and a chalk
    circle rewarded attention with a theory to build; the shrine rewarded
    attention with nothing at all, because its reward was paid out somewhere
    else to something else. Studying the chalk circle was the better-reasoned
    choice, and he made it three runs running.

    Leaks nothing: the room is already his -- he is standing in it -- and the
    text names no doorway, no direction and no other chamber. The interlude
    keeps its meal, which is a real reward for finishing; it simply stops
    being the ONLY thing that ever felt good.
    """
    from core.db import q, qi
    import json as _json
    try:
        row = q("SELECT id FROM turns WHERE chat_id=? ORDER BY idx DESC "
                "LIMIT 1", (chat_id,), one=True)
        if row:
            from mind.memory import add_memory
            # salience is POSITIONAL, before the body -- same call shape the
            # interlude uses. Passing the body into that slot and salience as
            # a keyword raises, and the guard below then swallows the whole
            # block: the first two arrivals paid nothing on contact because
            # of exactly that, silently.
            add_memory(chat_id, char_id, row["id"], "episodic", "experienced",
                       0.95,
                       f"You came into the shrine chamber and the light off "
                       "the water went over you, and it was warm, and the air "
                       "smelled of bread. You had got there. Whatever the "
                       "gods keep, they keep it here, and you were standing "
                       "in it.",
                       category="event",
                       gist="Reached the shrine and stood in it.",
                       location=_rid(GOAL), valence=0.9, arousal=0.5,
                       emotional_context="arrival; the thing itself, not the "
                                         "meal afterwards")
        st_row = q("SELECT state FROM chat_chars WHERE chat_id=? AND char_id=?",
                   (chat_id, char_id), one=True)
        if st_row:
            st = _json.loads(st_row["state"] or "{}")
            active = st.setdefault("active_state", {})
            hed = active.get("hedonic")
            if not isinstance(hed, dict):
                hed = {"pain": 0.0, "pleasure": 0.0, "source": "",
                       "charge": 0.0}
            hed["pleasure"] = max(float(hed.get("pleasure") or 0.0), 0.85)
            hed["pain"] = 0.0
            hed["source"] = "standing in the shrine at the end of the maze"
            active["hedonic"] = hed
            # The room's NAME becomes his the beat he stands in it, and the
            # project that has been steering him blind can finally say where
            # it is going. Until now the commission named no chamber on
            # purpose (that would have been the leak); from here the
            # destination resolver can route on the project text itself,
            # which is what makes it a durable fallback when every goal and
            # intention above it has died.
            goal_name = f"Chamber {_rid(GOAL)[1:]}"
            for proj in (st.setdefault("interior", {})
                         .setdefault("projects", [])):
                text = str(proj.get("project") or "")
                if "shrine" in text.lower() and goal_name not in text:
                    proj["project"] = f"{text.rstrip('.')}. The shrine is " \
                                      f"{goal_name}."
            qi("UPDATE chat_chars SET state=? WHERE chat_id=? AND char_id=?",
               (_json.dumps(st), chat_id, char_id))
        print("    REACHED THE SHRINE -- reward paid on contact", flush=True)
    except Exception as exc:                            # pragma: no cover
        print(f"    shrine reward not applied ({exc})")


# Fields worth watching, in the order they make sense to read: what he thought
# privately, what he weighed, what he chose, what he concluded, how he felt.
_THINK_FIELDS = (
    "private_thought", "observations_used", "response_candidates", "sequence",
    "mind_model_updates", "belief_updates", "association_updates",
    "active_state", "appraisal", "manifest",
)


def _dump_thoughts(path, run_no, beat, where, out, resolved, stalled=None,
                   reasoning=""):
    """Append one beat of the character's own output, readable rather than raw.

    Everything the character emits is dropped on the floor by this harness --
    it calls the stages directly, so nothing reaches the steps/variants tables
    the app would normally render. Watching a navigation experiment without
    seeing the navigator's reasoning means guessing at motive from a trail of
    room ids.

    `stalled` marks a beat that raised. Those are the ones worth reading: a
    stall is where a model's output and a schema disagreed, and the block
    below is exactly what the failing stage was handed.
    """
    head = f"run {run_no} | beat {beat} | in {where}"
    if stalled:
        head += f"  ***  STALLED: {stalled}"
    lines = [f"\n{'='*72}", head, "=" * 72]
    if stalled and not out:
        lines.append("\n(the character stage itself raised -- nothing to show)")
    # The thinking model's own trace, which for such a model is where the
    # decision actually happens -- the structured output below is only its
    # conclusion. The harness drives stages directly and never calls
    # save_step, so the engine's variants.reasoning column never fills here
    # and this is the only place it can be read.
    _think = str(reasoning or "").strip()
    if _think:
        lines.append(f"\n-- reasoning --\n{_think}")
    for field in _THINK_FIELDS:
        value = out.get(field)
        if value in (None, "", [], {}):
            continue
        if isinstance(value, str):
            lines.append(f"\n-- {field} --\n{value}")
        else:
            lines.append(f"\n-- {field} --\n"
                         + json.dumps(value, indent=2, ensure_ascii=False))
    summary = str((resolved or {}).get("summary") or "").strip()
    if summary:
        lines.append(f"\n-- director resolved --\n{summary}")
    with open(path, "a", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
        fh.flush()


def render_grid(walls, here, seen, path=()):
    """The maze as ASCII, with walls, where he is, and where he has been.

    #  wall        @  him now
    .  unvisited   o  visited this run      *  on the optimal path
    """
    seen = set(seen or ())
    path = set(path or ())
    lines = ["+" + "---+" * GRID]
    for r in range(GRID):
        mid, bottom = "|", "+"
        for c in range(GRID):
            rid = _rid((r, c))
            if rid == here:
                glyph = " @ "
            elif rid == _rid(GOAL):
                glyph = " X "
            elif rid in seen:
                glyph = " o "
            elif (r, c) in path:
                glyph = " * "
            else:
                glyph = " . "
            east_open = (r, c + 1) in walls.get((r, c), ())
            mid += glyph + (" " if east_open else "|")
            south_open = (r + 1, c) in walls.get((r, c), ())
            bottom += ("   +" if south_open else "---+")
        lines.append(mid)
        lines.append(bottom)
    return "\n".join(lines)


def metrics(visited, optimal):
    moves = [b for a, b in zip(visited, visited[1:]) if a != b]
    seen, backtracks = set(), 0
    for room in visited:
        if room in seen:
            backtracks += 1
        seen.add(room)
    reversals = sum(
        1 for a, b, c in zip(visited, visited[1:], visited[2:]) if a == c and a != b)
    return {
        "steps": len(visited) - 1,
        "moves": len(moves),
        # Beats spent without changing room. High means the character is
        # deliberating or observing rather than navigating -- a motivation
        # property, not a navigation one, and the two must not be summed.
        "idle_beats": (len(visited) - 1) - len(moves),
        "unique": len(seen),
        "backtracks": backtracks,
        "reversals": reversals,
        "reached": visited[-1] == _rid(GOAL),
        "optimal": optimal,
        # Excess is over MOVES: the honest navigation score.
        "excess": len(moves) - optimal if visited[-1] == _rid(GOAL) else None,
    }


