def character_sheet(name="Vesk"):
    """Authored so repetition does not extinguish the drive -- and so nothing
    ELSE competes with walking.

    Getting this wrong is easy and it invalidates the run. The first version
    gave him "notice and remember what makes each chamber different" as a goal
    and framed circuits as "a devotion, not a chore", to stop repetition
    exhausting the drive. He complied exactly: he stopped and studied every
    room for two to five beats before moving one, narrating his mental map
    settling into place. Every room he entered was on the optimal path -- the
    navigation was fine and the experiment was measuring the character sheet.

    So: the durable motivation stays (a goal satisfied once would strain toward
    rupture by run three, and then we would be measuring the motivation model),
    but the reward is now attached to ARRIVING and to walking the route
    fluently, never to studying it in place. Learning the maze is framed as
    something that happens BY walking it, which is also what is true.
    """
    from character_schema import default_character_data, normalize_character_data
    sheet = default_character_data(name)
    sheet["identity"]["pronouns"] = {
        "subject": "he", "object": "him", "possessive": "his"}
    sheet["knowledge"] = dict(sheet.get("knowledge") or {})
    sheet["knowledge"]["public_history"] = (
        f"{name} is a courier who runs the shrine-maze daily. Speed is the "
        "whole of his craft and he is proud of it: he keeps moving, takes the "
        "turn he judges best without stopping to deliberate, and treats "
        "standing still in a corridor as the one real failure. He has run it "
        "often enough to trust that the route comes back to him in his feet "
        "rather than by studying the walls."
    )
    sheet["psychology"] = dict(sheet.get("psychology") or {})
    sheet["psychology"]["traits"] = [
        "brisk", "decisive", "impatient with standing still", "sure-footed",
    ]
    sheet["psychology"]["values"] = ["a fast clean run", "never breaking stride"]
    sheet["initial_state"] = dict(sheet.get("initial_state") or {})
    sheet["initial_state"]["goals"] = [
        {"goal": "Reach the shrine at the far corner as fast as possible.",
         "priority": 0.9},
        # Deliberately NOT "never deliberate". The first version said that and
        # he obeyed it too well -- the thought stream showed him rejecting
        # "deliberate on paths" as a norm violation (inhibition 0.8), so he was
        # optimising for stride rather than for arriving. Both that and the
        # original devotional room-studying are the sheet distorting the
        # measurement; what is wanted is a character who thinks WHILE walking.
        {"goal": "Keep moving -- decide as you walk rather than standing "
                 "still to decide. Choosing the turn is part of moving, not a "
                 "pause in it.", "priority": 0.95},
        {"goal": "Beat your own best time on this run.", "priority": 0.6},
    ]
    return normalize_character_data(sheet)


# Model routing and provider credentials live in settings/providers, so a fresh
# scratch DB has no model for any role and a live run dies on the first call.
# host_pw/host_secret are deliberately NOT carried: no server runs here, and a
# throwaway experiment DB has no business holding auth material.
_SETTINGS_TO_CARRY = (
    "agent_models", "openrouter_routing", "active_preset", "prompt_presets",
    "reasoning_effort", "max_output_tokens", "nsfw_enabled",
)


def carry_model_config(source_db, db_path):
    """Copy the model config from the real DB into the scratch DB.

    Two halves, and BOTH are needed. `settings.agent_models` says which model
    each role uses; the `providers` table holds the connections those models
    resolve through. Carrying only the first gets you past "No model configured
    for role X" straight into "No USABLE model configured for role X".

    This does put the source DB's API keys into the scratch file -- a throwaway
    under the system temp dir, never committed, but worth knowing it is there.
    """
    import sqlite3
    if not source_db or not os.path.exists(source_db):
        print(f"  ! no source DB at {source_db!r}; a live run will have no "
              f"model configured")
        return 0, 0
    src = sqlite3.connect(f"file:{source_db}?mode=ro", uri=True)
    src.row_factory = sqlite3.Row
    from db import qi
    n_set = 0
    for row in src.execute("SELECT key,value FROM settings"):
        if row["key"] not in _SETTINGS_TO_CARRY:
            continue
        qi("INSERT INTO settings(key,value) VALUES(?,?) "
           "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
           (row["key"], row["value"]))
        n_set += 1
    n_prov = 0
    for row in src.execute("SELECT * FROM providers"):
        qi("INSERT INTO providers(id,name,kind,base_url,api_key,enabled) "
           "VALUES(?,?,?,?,?,?) ON CONFLICT(id) DO UPDATE SET "
           "name=excluded.name, kind=excluded.kind, base_url=excluded.base_url, "
           "api_key=excluded.api_key, enabled=excluded.enabled",
           (row["id"], row["name"], row["kind"], row["base_url"],
            row["api_key"], row["enabled"]))
        n_prov += 1
    src.close()
    return n_set, n_prov


def ablate_affordances():
    """Put the character back on the pre-change payload.

    Two things go: the visited/unvisited marking on each exit, and the location
    cue on recall. Everything else -- prompts, stages, models -- is untouched,
    so a difference between the arms is attributable to these.
    """
    import agents.character as ch
    import memory as mem
    # **kw so the stub survives the annotator growing keyword inputs
    # (known_exits/here_rid/place_graph/...) -- ablation means "mark nothing",
    # not "crash on the inputs you would have marked from".
    ch._annotate_known_exits = lambda digest, scene, visited, **kw: digest
    _search = mem.search_memories

    def _no_place_cue(*a, **kw):
        kw["here"] = None
        return _search(*a, **kw)
    mem.search_memories = _no_place_cue


def set_reasoning_effort(spec):
    """Override reasoning effort, as 'role=level,...' or a bare level for all.

    Worth reaching for: perception defaults to "high" in the working config AND
    now makes one call per observer since the per-observer split, so it is
    routinely the second-largest latency line in a run -- while what it
    contributes to a navigation experiment is a room description.
    """
    import json as _json
    from db import q, qi
    row = q("SELECT value FROM settings WHERE key='reasoning_effort'", one=True)
    cfg = _json.loads(row["value"]) if row and row["value"] else {}
    if "=" not in str(spec):
        cfg = {"default": str(spec)}
    else:
        for pair in str(spec).split(","):
            role, _, level = pair.partition("=")
            if role.strip() and level.strip():
                cfg[role.strip()] = level.strip()
    qi("INSERT INTO settings(key,value) VALUES('reasoning_effort',?) "
       "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
       (_json.dumps(cfg),))
    return cfg


# The measured-best split. Character is the only role that DELIBERATES -- it
# chooses which doorway to take -- and it is the only one a fast model failed
# at: inception/mercury-2 on every role reached the goal 0/2 with 12-15
# backtracks and only 15-18 unique rooms, churning in one region rather than
# exploring, while grok-4.20 on every role walked the exact optimal path.
# Everything else is transformation: perception renders a room, the director
# resolves a declared move into a position, mapping and utility keep books.
# Mercury holds those at 0.7-1.6s against grok's 7-12s.
#
# Result: ~13.4s per beat against ~39s, with character then accounting for
# ~95% of what remains -- so it is the only role worth paying for.
_PRESETS = {
    "fast": {
        "model": ["3:inception/mercury-2",
                  "character_mid=3:x-ai/grok-4.20",
                  "character_major=3:x-ai/grok-4.20",
                  "character_bg=3:x-ai/grok-4.20"],
        "reasoning": "low",
    },
}


def apply_model_specs(specs):
    """Apply one or more `--model` specs.

    Each is `provider:model` (every role) or `role=provider:model` (that role).
    Repeatable, because the useful experiment usually needs two at once: the
    roles under test pinned to one model, and a support role -- perception --
    left on, or moved to, something fast.
    """
    applied = []
    for spec in specs or []:
        for part in str(spec).split(","):
            part = part.strip()
            if not part:
                continue
            role, sep, target = part.partition("=")
            if sep:
                applied.append((role.strip(),
                                force_single_model(target, [role.strip()])))
            else:
                applied.append(("*", force_single_model(part)))
    return applied


def force_single_model(spec, roles=None):
    """Point the named roles at one model (every configured role by default).

    Holding the model constant makes a result attributable -- but forcing ALL
    roles is usually the wrong trade. In a navigation experiment the character
    and the director are what is under test; perception only renders the room,
    and it needs to be constant ACROSS ARMS, not identical to the character's
    model. Forcing it too moved perception off a fast dedicated provider onto a
    slower shared one and roughly doubled wall-clock for no experimental gain.

    Roles are normally a MIX -- director on grok, perception on glm, character
    on whatever `default` is -- which is right for play and wrong for an
    experiment: if the character navigates badly you cannot tell whether that
    is the character model, the director resolving its moves, or the perception
    model describing the room. Holding the model constant makes the result
    attributable.
    """
    import json as _json
    from db import q, qi
    provider_id, _, model = str(spec).partition(":")
    if not model:
        raise SystemExit("--model must be '<provider_id>:<model>'")
    row = q("SELECT value FROM settings WHERE key='agent_models'", one=True)
    cfg = _json.loads(row["value"]) if row and row["value"] else {}
    forced = {"provider": int(provider_id), "model": model, "fallbacks": []}
    targets = [r.strip() for r in (roles or []) if r.strip()] or list(cfg)
    for role in targets:
        cfg[role] = dict(forced)
    if not roles:
        cfg["default"] = dict(forced)
    qi("INSERT INTO settings(key,value) VALUES('agent_models',?) "
       "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
       (_json.dumps(cfg),))
    return model


