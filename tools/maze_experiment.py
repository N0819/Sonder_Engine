def run_interlude(chat_id, char_id, name, run_no, reached, turn_id):
    """What happens to him BETWEEN runs, told to him as his own experience.

    Runs used to be separated by a bare teleport: he arrived somewhere, and
    the next thing in his head was standing at the entrance with no cause.
    That is a reality-break, and a mind that reasons will explain it -- run 1
    of the aborted arm produced exactly that shape of belief ("the maze layout
    sometimes differs from memory") from a smaller discontinuity, and then
    discounted its own true map for the rest of the run. An experiment about
    whether a character LEARNS a space cannot afford to teach them the space
    is unreliable.

    So the boundary is narrated: he finishes, he is fed, he is carried back.
    Three properties matter and none is decoration:

    * It is his OWN experience -- arrival, a meal, the return trip. It names
      no room, no doorway, no direction, and nothing about the maze's shape.
      A reward that leaked layout would hand him by fiat what the arm exists
      to measure whether he can learn.
    * The food is a real reward, not flavour text: positive valence and a
      pleasure reading, so finishing has a felt consequence. He is a courier
      who is proud of a fast clean run; a hot meal at the end is what that
      pride is FOR.
    * The teleport is stated as a fact he was told, not left to be inferred.
      He knows he was carried back. He does not have to invent a maze that
      moves.
    """
    fed = ("a bowl of hot spiced barley and a cup of dark beer, pressed into "
           "your hands still steaming")
    if reached:
        body = (f"You reached the shrine at the heart of the maze. The "
                f"keepers fed you well for it -- {fed} -- and you ate sitting "
                f"down, which you almost never do. Then they walked you back "
                f"to the entrance and set you at the threshold to run it "
                f"again.")
        valence, arousal, salience = 0.8, 0.4, 0.85
    else:
        body = (f"The keepers called the run before you reached the shrine. "
                f"They fed you anyway -- {fed} -- and you ate it standing, "
                f"chewing over where the way had gone wrong. Then they walked "
                f"you back to the entrance and set you at the threshold to "
                f"run it again.")
        valence, arousal, salience = 0.3, 0.35, 0.8

    try:
        from memory import add_memory
        add_memory(chat_id, char_id, turn_id, "episodic", "experienced",
                   salience, body, category="event",
                   gist=("Finished a run, was fed, and was carried back to "
                         "the entrance to start again."),
                   location=_rid(START), valence=valence, arousal=arousal,
                   emotional_context="fed and rested; set going again")
    except Exception as exc:                       # pragma: no cover
        print(f"    interlude: memory not written ({exc})")

    # The meal as a felt state, not merely a remembered one. Written into
    # active_state.hedonic where resolve_hedonic keeps it; `charge` is left
    # alone deliberately -- a satisfied hunger is a RESOLVED state, and
    # integrating it as unresolved drive is the failure DESIGN_SURFACE_COMFORT
    # names (a saturated body manufactured out of contentment).
    try:
        from db import q, qi
        import json as _json
        # chat_chars is keyed on (chat_id, char_id) -- it has no `id`.
        row = q("SELECT state FROM chat_chars WHERE chat_id=? AND char_id=?",
                (chat_id, char_id), one=True)
        if row:
            st = _json.loads(row["state"] or "{}")
            active = st.setdefault("active_state", {})
            hedonic = active.get("hedonic")
            if not isinstance(hedonic, dict):
                hedonic = {"pain": 0.0, "pleasure": 0.0, "source": "",
                           "charge": 0.0, "saturated": False}
            hedonic["pleasure"] = max(float(hedonic.get("pleasure") or 0.0), 0.45)
            hedonic["pain"] = 0.0
            hedonic["source"] = "hot barley and dark beer after the run"
            active["hedonic"] = hedonic
            qi("UPDATE chat_chars SET state=? WHERE chat_id=? AND char_id=?",
               (_json.dumps(st), chat_id, char_id))
    except Exception as exc:                       # pragma: no cover
        print(f"    interlude: reward not applied ({exc})")

    print(f"    interlude: run {run_no} ended "
          f"({'reached the shrine' if reached else 'called short'}), fed, "
          f"returned to {_rid(START)}")


def position_of(chat_id, name):
    from db import wget
    return ((wget(chat_id, "scene", {}) or {}).get("positions") or {}).get(name)


def _random_agent_handler(walls, name, rng):
    """The control: uniform choice among legal exits, no memory, no LLM.

    `rng` is threaded in rather than created here: built per CALL, it reseeded
    every step and produced a deterministic oscillation (56 reversals in 60
    steps, 5 rooms seen) that looked like a pathological walker rather than the
    memoryless one this is supposed to be.
    """
    def handler(ctx, cid, nonce):
        here = position_of(ctx.chat.id, name)
        cell = next(c for c in walls if _rid(c) == here)
        nxt = rng.choice(sorted(walls[cell]))
        return {
            "name": name,
            "sequence": [{
                "type": "action", "verb": "walk",
                "attempt": f"walk into the chamber to the {_DIRS[(nxt[0]-cell[0], nxt[1]-cell[1])]}",
                "observable": "walks to the next chamber",
                "commitment": "uncontested", "targets": [],
                "intended_effects": [], "asserted_effects": [],
            }],
            "_forced_move": _rid(nxt),
        }
    return handler


# perception_act runs BEFORE the character, because character_step reads its
# view from perception_act (agents/character.py) -- NOT from perception_outcome,
# which renders the aftermath for the next beat. Omitting it meant the character
# fell through to character.py's "You register nothing new this beat." fallback
# on every single beat: navigating a maze having never been shown a room,
# working only from the exit list. Every measurement taken before this was of a
# blind character.
_PRE_CHARACTER = ("perception_act",)

# Then the rest of the beat. mapping_quick reconciles against world/lore and
# changes what reaches director_resolve.
_LLM_CHAIN = ("mapping_quick", "director_resolve", "perception_outcome", "commit")


def install_scripted_models(name, walls):
    """Stub the model layer, keyed on the ROLE (`_agent_json`'s first
    positional). The character picks a legal exit; everything downstream is the
    real stage code, so this exercises director_resolve -> commit for free."""
    import agents.character as ch, agents.perception as pc
    import agents.director as dr, agents.mapping as mp
    import providers
    rng = random.Random(99)

    def _fake(role, step, prompt, payload, **kw):
        if role == "character":
            here = payload.get("self", {}).get("room") or ""
            return {"name": name, "private_thought": "",
                    "sequence": [{"type": "action", "verb": "walk",
                                  "attempt": "walk through the open archway",
                                  "observable": "walks through the archway",
                                  "commitment": "uncontested", "targets": [],
                                  "intended_effects": [], "asserted_effects": []}],
                    "active_state": {"mood": "steady", "goal": "reach the shrine"}}
        if role == "director":
            here = _scripted_here[0]
            cell = next(c for c in walls if _rid(c) == here)
            nxt = rng.choice(sorted(walls[cell]))
            return {"resolved_event": f"{name} walks on.", "summary": "A step.",
                    "dialogue_log": [], "obligations": [],
                    "changes_asserted": [], "fact_adjudications": [],
                    "state_diff": {"positions": {name: _rid(nxt)}}}
        if role == "perception":
            return {"views": {str(p["id"]): "A stone chamber."
                              for p in (payload.get("perceivers") or [])}}
        return {}

    for mod in (ch, pc, dr, mp):
        mod._agent_json = _fake
    providers.chat_complete = lambda *a, **k: "{}"


_scripted_here = [_rid(START)]


def run_once(chat_id, char_id, name, walls, *, agent, max_steps, turn_base,
             verbose, rng=None, show_grid=False, optimal_path=(),
             collect_trace=False, think_path=None, run_no=0,
             resume_from=0, resume_visited=None, checkpoint=None):
    """One traversal. Returns the ordered list of rooms occupied."""
    import db as _db
    from db import qi, wget, wset
    from pipeline_context import PipelineContext, ChatData, TurnData
    from scene import active_cast
    import agents.runtime as runtime

    # On resume the position is already in the DB -- it is where he stopped,
    # not the start -- so the route is restored rather than begun.
    visited = list(resume_visited or []) or [position_of(chat_id, name)]
    stalls = []
    trace = [] if collect_trace else None
    for step in range(resume_from, max_steps):
        # Taken from the DB rather than counted in this process. `turn_base +=
        # len(visited)` undercounted: a STALLED beat inserts its turn row and
        # then skips the append, so every stall left the next run starting one
        # index low and eventually colliding on (chat_id, idx). It never bit
        # while the character model did not stall, which is exactly the kind
        # of bug that waits for the one arm you care about. One small query a
        # beat is nothing beside the LLM calls, and it cannot be miscounted.
        _max = _db.q("SELECT MAX(idx) AS m FROM turns WHERE chat_id=?",
                     (chat_id,), one=True)
        idx = int((_max or {})["m"] or 0) + 1
        turn_id = qi(
            "INSERT INTO turns(chat_id,idx,player_input,created) VALUES(?,?,?,?)",
            (chat_id, idx, "", time.time()))
        row = _db.q("SELECT * FROM chats WHERE id=?", (chat_id,), one=True)
        ctx = PipelineContext(
            chat=ChatData(id=chat_id, name=row["name"], persona_id=row["persona_id"],
                          lorebook_id=row["lorebook_id"], scenario=row["scenario"],
                          created=row["created"]),
            turn=TurnData(id=turn_id, chat_id=chat_id, idx=idx,
                          player_input="", created=time.time()),
            cast=active_cast(chat_id),
            input="",
        )
        # No player this beat: the sequence is empty and flow asks for nothing.
        # `reactors` is load-bearing, not boilerplate: perception_act builds a
        # perceiver ONLY for a character listed here, so an empty list meant
        # the character was never a perceiver and character_step fell through
        # to "You register nothing new this beat." on every beat. In real play
        # director_interpret populates this from the player's act; with no
        # player, the character is the only mind in the scene and always
        # perceives.
        ctx["director_interpret"] = {
            "sequence": [],
            "flow": {"needs_mapping": False, "reactors": [char_id],
                     "resolution_flags": {}},
            "authorial_offers": [],
        }

        if agent in ("random",):
            result = _random_agent_handler(walls, name, rng)(ctx, char_id, 0)
            ctx[f"character:{char_id}"] = result
            # The control does not exercise the director; move it directly so
            # the baseline measures NAVIGATION, not the resolver.
            sc = wget(chat_id, "scene", {}) or {}
            sc.setdefault("positions", {})[name] = result["_forced_move"]
            wset(chat_id, "scene", sc)
        else:
            _scripted_here[0] = position_of(chat_id, name)
            # A model that returns a slightly-off shape raises out of
            # complete_validated_json and would otherwise end a multi-hour
            # unattended run at whatever step it happened on. Retry the beat
            # once, then skip it: a skipped beat is a stalled character, which
            # the metrics already record honestly as a step with no move.
            try:
                for key in _PRE_CHARACTER:
                    ctx[key] = runtime.compute_step(key, ctx, 0)
                ctx[f"character:{char_id}"] = runtime.compute_step(
                    f"character:{char_id}", ctx, 0)
                # Grabbed HERE, not at the end of the beat. The ContextVar
                # holds whichever call set it last, and the four stages below
                # are all mercury -- which returns no reasoning, so it
                # overwrites the character's with nothing. Read at dump time
                # it was always empty, which looked like the model not
                # exposing a trace rather than us reading the wrong moment.
                try:
                    from providers import last_reasoning as _lr
                    char_reasoning = str(_lr.get() or "")
                except Exception:
                    char_reasoning = ""
                for key in _LLM_CHAIN:
                    ctx[key] = runtime.compute_step(key, ctx, 0)
            except Exception as exc:
                stalls.append(f"step {step + 1}: {type(exc).__name__}: {exc}")
                print(f"    step {step + 1:3}  STALLED "
                      f"({type(exc).__name__}: {str(exc)[:120]})", flush=True)
                # A stall the run cannot recover from must END it, not be
                # retried sixty times. Out of credit, a revoked key or a dead
                # provider fails INSTANTLY, so the beat loop stops being rate
                # limited by the network and spins at full speed: observed
                # live, an exhausted OpenRouter balance turned into 272
                # identical stalls in seconds, burying 26 real beats of
                # results under them and reporting a stall count that looked
                # like a model problem.
                _fatal = ("402", "401", "403", "Insufficient credits",
                          "No usable model configured")
                if any(sig in str(exc) for sig in _fatal):
                    print(f"    ABORTING RUN -- unrecoverable: "
                          f"{str(exc)[:160]}", flush=True)
                    raise SystemExit(
                        "maze: aborting, the provider cannot serve this run "
                        f"({str(exc)[:200]}). Completed beats and the "
                        "checkpoint are intact -- fix the cause and --resume.")
                # Dump whatever the character DID produce before skipping.
                # This used to `continue` straight past the dump, which made
                # every stalled beat invisible -- and a stalled beat is the
                # one worth reading, because it is where a model's output and
                # the schema disagreed. Diagnosing a director failure meant
                # inferring the character's output from the beats either side
                # of it. What exists at this point is exactly what the failing
                # stage was handed.
                if think_path:
                    _dump_thoughts(
                        think_path, run_no, step + 1, visited[-1],
                        ctx.get(f"character:{char_id}") or {},
                        ctx.get("director_resolve") or {},
                        stalled=f"{type(exc).__name__}: {exc}",
                        reasoning=locals().get("char_reasoning", ""))
                continue

        if agent != "random":
            _out = ctx.get(f"character:{char_id}") or {}
            _res = ctx.get("director_resolve") or {}
            if think_path:
                _dump_thoughts(think_path, run_no, step + 1, visited[-1],
                               _out, _res, reasoning=char_reasoning)
            if trace is not None:
                trace.append({
                    "beat": step + 1,
                    "from": visited[-1],
                    "private_thought": str(_out.get("private_thought") or "")[:300],
                    "declared": [
                        {"type": e.get("type"), "verb": e.get("verb"),
                         "attempt": str(e.get("attempt") or e.get("text") or "")[:200]}
                        for e in (_out.get("sequence") or []) if isinstance(e, dict)],
                    "resolved": str(_res.get("summary") or "")[:200],
                    # The view the character actually navigated on: a
                    # perception model can return schema-valid output too thin
                    # to recognise a room from, which surfaces as worse
                    # navigation rather than as an error.
                    "view": {
                        k: str(v)[:400] for k, v in
                        ((ctx.get("perception_outcome") or {}).get("views")
                         or {}).items()},
                })

        here = position_of(chat_id, name)
        visited.append(here)
        if verbose:
            print(f"    step {step + 1:3}  {here}")
        if show_grid:
            print(render_grid(walls, here, visited, optimal_path))
            print(f"    step {step + 1} | at {here} | "
                  f"{len(set(visited))} of {GRID * GRID} chambers seen",
                  flush=True)
        if checkpoint:
            # After every beat, because the whole point is that a run
            # interrupted to fix code loses at most the beat in flight. The
            # DB already holds everything the character IS -- memory, mind
            # models, chat_chars.state, his position -- so what has to be
            # written here is only what lives in this process: which run and
            # beat, the route so far, and the rng.
            checkpoint(run_no, step + 1, visited)
        if here == _rid(GOAL):
            break
    if stalls:
        print(f"    ({len(stalls)} stalled beats this run)")
    return visited, (trace or [])


# Fields worth watching, in the order they make sense to read: what he thought
# privately, what he weighed, what he chose, what he concluded, how he felt.
_THINK_FIELDS = (
    "private_thought", "observations_used", "response_candidates", "sequence",
    "mind_model_updates", "belief_updates", "association_updates",
    "active_state", "appraisal", "manifest",
)


def _dump_thoughts(path, run_no, beat, where, out, resolved, stalled=None,
                   reasoning=""):
    """Append one beat of the character's own output, readable rather than raw.

    Everything the character emits is dropped on the floor by this harness --
    it calls the stages directly, so nothing reaches the steps/variants tables
    the app would normally render. Watching a navigation experiment without
    seeing the navigator's reasoning means guessing at motive from a trail of
    room ids.

    `stalled` marks a beat that raised. Those are the ones worth reading: a
    stall is where a model's output and a schema disagreed, and the block
    below is exactly what the failing stage was handed.
    """
    head = f"run {run_no} | beat {beat} | in {where}"
    if stalled:
        head += f"  ***  STALLED: {stalled}"
    lines = [f"\n{'='*72}", head, "=" * 72]
    if stalled and not out:
        lines.append("\n(the character stage itself raised -- nothing to show)")
    # The thinking model's own trace, which for such a model is where the
    # decision actually happens -- the structured output below is only its
    # conclusion. The harness drives stages directly and never calls
    # save_step, so the engine's variants.reasoning column never fills here
    # and this is the only place it can be read.
    _think = str(reasoning or "").strip()
    if _think:
        lines.append(f"\n-- reasoning --\n{_think}")
    for field in _THINK_FIELDS:
        value = out.get(field)
        if value in (None, "", [], {}):
            continue
        if isinstance(value, str):
            lines.append(f"\n-- {field} --\n{value}")
        else:
            lines.append(f"\n-- {field} --\n"
                         + json.dumps(value, indent=2, ensure_ascii=False))
    summary = str((resolved or {}).get("summary") or "").strip()
    if summary:
        lines.append(f"\n-- director resolved --\n{summary}")
    with open(path, "a", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
        fh.flush()


def render_grid(walls, here, seen, path=()):
    """The maze as ASCII, with walls, where he is, and where he has been.

    #  wall        @  him now
    .  unvisited   o  visited this run      *  on the optimal path
    """
    seen = set(seen or ())
    path = set(path or ())
    lines = ["+" + "---+" * GRID]
    for r in range(GRID):
        mid, bottom = "|", "+"
        for c in range(GRID):
            rid = _rid((r, c))
            if rid == here:
                glyph = " @ "
            elif rid == _rid(GOAL):
                glyph = " X "
            elif rid in seen:
                glyph = " o "
            elif (r, c) in path:
                glyph = " * "
            else:
                glyph = " . "
            east_open = (r, c + 1) in walls.get((r, c), ())
            mid += glyph + (" " if east_open else "|")
            south_open = (r + 1, c) in walls.get((r, c), ())
            bottom += ("   +" if south_open else "---+")
        lines.append(mid)
        lines.append(bottom)
    return "\n".join(lines)


def metrics(visited, optimal):
    moves = [b for a, b in zip(visited, visited[1:]) if a != b]
    seen, backtracks = set(), 0
    for room in visited:
        if room in seen:
            backtracks += 1
        seen.add(room)
    reversals = sum(
        1 for a, b, c in zip(visited, visited[1:], visited[2:]) if a == c and a != b)
    return {
        "steps": len(visited) - 1,
        "moves": len(moves),
        # Beats spent without changing room. High means the character is
        # deliberating or observing rather than navigating -- a motivation
        # property, not a navigation one, and the two must not be summed.
        "idle_beats": (len(visited) - 1) - len(moves),
        "unique": len(seen),
        "backtracks": backtracks,
        "reversals": reversals,
        "reached": visited[-1] == _rid(GOAL),
        "optimal": optimal,
        # Excess is over MOVES: the honest navigation score.
        "excess": len(moves) - optimal if visited[-1] == _rid(GOAL) else None,
    }


def main():
    global GRID, GOAL, START
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--agent", choices=("random", "scripted", "llm"),
                    default="random")
    ap.add_argument("--runs", type=int, default=5)
    ap.add_argument("--max-steps", type=int, default=40)
    ap.add_argument("--db", default=None)
    ap.add_argument("--model", action="append", default=None,
                    help="'<provider>:<model>' for every role, or "
                         "'<role>=<provider>:<model>' for one. Repeatable. "
                         "Without it each role keeps whatever the source DB "
                         "configured, which is usually a mix.")
    ap.add_argument("--size", type=int, default=GRID,
                    help="maze is NxN (default 6). --grid is the ASCII render.")
    ap.add_argument("--svg", default=None,
                    help="run an AUTHORED maze from an orthogonal maze SVG "
                         "instead of generating one. Overrides --size/--algo/"
                         "--braid, and takes start and goal from the entrance "
                         "and exit gaps in the border. See tools/mazes/.")
    ap.add_argument("--algo", choices=sorted(_CARVERS), default="dfs",
                    help="carver. dfs walks, so it makes long winding "
                         "corridors with few branch points -- easy to follow. "
                         "kruskal/prim branch evenly and roughly triple the "
                         "junctions at the same size.")
    ap.add_argument("--braid", type=float, default=0.0,
                    help="fraction of dead ends opened into LOOPS, 0-1. A "
                         "perfect maze (0) has one path between any two cells, "
                         "so there is no better route to learn and no way to "
                         "tell being lost from backing out of a dead end.")
    ap.add_argument("--preset", choices=sorted(_PRESETS), default=None,
                    help="named model/effort configuration; --model and "
                         "--reasoning override it")
    ap.add_argument("--reasoning", default=None,
                    help="'role=level,...' or a bare level for all")
    ap.add_argument("--settings-from", default="engine.db",
                    help="DB to copy model/provider settings from "
                         "(read-only; never written to)")
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument("--state", help=(
        "checkpoint file, rewritten after every beat. Pair with --resume to "
        "stop an experiment, change code, and carry on from the beat after "
        "the last one completed. Costs nothing when unused."))
    ap.add_argument("--resume", help=(
        "resume from this checkpoint instead of starting over: reuses its "
        "database, so accumulated memory, mind models and route knowledge "
        "survive a code change. Refuses to resume onto a different maze. "
        "Usually the same path as --state."))
    ap.add_argument("--ablate-affordances", action="store_true",
                    help="disable the visited-exit markers and the "
                         "location-cued recall, so the SAME model can be run "
                         "with and without them. A/B by runtime switch rather "
                         "than by checking out an older commit, so the two "
                         "arms are otherwise byte-identical.")
    ap.add_argument("--grid", action="store_true",
                    help="print the maze after every step")
    ap.add_argument("--think", default=None,
                    help="write the character's FULL output to this file, one "
                         "readable block per beat. The harness drives stages "
                         "directly and never calls save_step, so a character's "
                         "reasoning otherwise leaves no trace anywhere.")
    ap.add_argument("--out", default=None,
                    help="append per-run results here as JSON lines; written "
                         "and flushed after each run so an interrupted "
                         "experiment still yields its completed runs")
    ap.add_argument("--go", action="store_true",
                    help="required for --agent llm; it spends real tokens")
    args = ap.parse_args()

    if args.preset:
        preset = _PRESETS[args.preset]
        args.model = args.model or list(preset["model"])
        args.reasoning = args.reasoning or preset["reasoning"]
        print(f"preset {args.preset!r}: {len(preset['model'])} model specs, "
              f"reasoning {preset['reasoning']}")

    if args.svg:
        walls, GRID, START, GOAL = maze_from_svg(args.svg)
        # Bound at import against the old (0, 0) start; the scripted agent
        # would otherwise begin in a room the character is not standing in.
        _scripted_here[0] = _rid(START)
        maze_label = f"{os.path.basename(args.svg)} authored"
    else:
        GRID = args.size
        GOAL = (GRID - 1, GRID - 1)
        walls = build_maze(grid=GRID, braid=args.braid, algo=args.algo)
        maze_label = f"{args.algo} braid={args.braid} seed={MAZE_SEED}"
    optimal = len(shortest_path(walls)) - 1
    st = maze_stats(walls, GRID)
    dec = deception_stats(walls, START, GOAL)
    print(f"maze {GRID}x{GRID} {maze_label} | {st['cells']} rooms, "
          f"{st['loops']} loops, {st['dead_ends']} dead ends, "
          f"{st['junctions']} junctions | {_rid(START)}->{_rid(GOAL)} "
          f"| optimal {optimal} moves")
    fingerprint = maze_fingerprint(walls, START, GOAL)
    print(f"  traps: {dec['off_path']} of {st['cells']} rooms off-route "
          f"({100*dec['off_path']//st['cells']}%), {dec['deep_traps']} false "
          f"branches 3+ deep, worst {dec['max_depth']} rooms, "
          f"mean {dec['mean_depth']}")

    if args.agent == "llm" and not args.go:
        calls = args.runs * args.max_steps * (len(_LLM_CHAIN) + len(_PRE_CHARACTER))
        print(f"maze: {GRID}x{GRID}, optimal path {optimal} moves")
        print(f"--agent llm would make UP TO ~{calls} LLM calls "
              f"({args.runs} runs x {args.max_steps} steps x "
              f"{len(_LLM_CHAIN)} stages + character).")
        print("Re-run with --go to spend that. Try --agent random first: it is "
              "free and validates the harness.")
        return 0

    # --- resume -------------------------------------------------------
    # A Python process cannot reload its own modules, so applying a fix found
    # mid-experiment means starting a new process. Without this that also
    # meant starting a new EXPERIMENT: hours of accumulated memory, mind
    # models and route knowledge thrown away to change one line. Since
    # everything the character IS already lives in the DB, the only thing
    # that had to be rescued was this process's own bookkeeping.
    resume = {}
    if args.resume:
        if not os.path.exists(args.resume):
            print(f"  no checkpoint at {args.resume} -- starting fresh")
        else:
            resume = json.load(open(args.resume, encoding="utf-8"))
            # Checkpoints written before fingerprinting existed carry only
            # grid+algo; fall back to that rather than refusing them outright.
            if resume.get("maze"):
                if resume["maze"] != fingerprint:
                    raise SystemExit(
                        f"checkpoint is maze {resume['maze']}; this invocation "
                        f"is maze {fingerprint} ({GRID}x{GRID} {maze_label}). "
                        "Resuming across mazes would carry one maze's route "
                        "knowledge into another.")
            elif int(resume.get("grid") or 0) != GRID or \
                    str(resume.get("algo") or "") != args.algo:
                raise SystemExit(
                    f"checkpoint is a {resume.get('grid')}x{resume.get('grid')} "
                    f"{resume.get('algo')} maze; this invocation is "
                    f"{GRID}x{GRID} {args.algo}. Resuming across mazes would "
                    "carry one maze's route knowledge into another.")

    db_path = resume.get("db") or args.db or tempfile.mkstemp(suffix=".maze.db")[1]
    if not resume and os.path.exists(db_path):
        os.remove(db_path)
    print(f"seed {MAZE_SEED} | agent={args.agent} | db={db_path}")

    if resume:
        import db as _db
        _db.configure(db_path)
        row = _db.q("SELECT id FROM chats ORDER BY id LIMIT 1", one=True)
        crow = _db.q("SELECT id,name FROM characters ORDER BY id LIMIT 1",
                     one=True)
        chat_id, char_id, name = row["id"], crow["id"], crow["name"]
        # A beat inserts its turn row BEFORE any stage runs, and the
        # checkpoint is written only once the beat completes. Kill the
        # process in between -- which is exactly what stopping to fix code
        # does -- and the DB holds a turn for a beat that never happened.
        # Resuming onto it collides on (chat_id, idx). Those rows belong to
        # no completed beat, so they go.
        _next_idx = int(resume.get("turn_base") or 1) + int(resume.get("beat") or 0)
        _orphans = _db.q("SELECT COUNT(*) AS n FROM turns WHERE chat_id=? "
                         "AND idx>=?", (chat_id, _next_idx), one=True)["n"]
        if _orphans:
            _db.q("DELETE FROM turns WHERE chat_id=? AND idx>=?",
                  (chat_id, _next_idx))
        print(f"  RESUMED at run {resume['run']} beat {resume['beat']} "
              f"-- {resume['beat']} beats and "
              f"{len(resume.get('rows') or [])} finished runs kept"
              + (f", {_orphans} incomplete beats discarded" if _orphans else ""))
    else:
        chat_id, char_id, name = setup(
            db_path, walls,
            source_db=args.settings_from if args.agent == "llm" else None,
            model=args.model if args.agent == "llm" else None,
            reasoning=args.reasoning if args.agent == "llm" else None)
    if args.agent == "scripted":
        install_scripted_models(name, walls)
    if args.ablate_affordances:
        ablate_affordances()
        print("  ABLATED: visited-exit markers and location-cued recall off")
    if args.out:
        # A self-describing header, written before any run. A results file
        # that records only routes cannot be read six weeks later: the same
        # `visited` list means different things on a different maze, and an
        # arm whose maze or code state has to be reconstructed from a shell
        # history is an arm that will eventually be compared against the
        # wrong baseline. Everything needed to rebuild the maze and identify
        # the tree that produced it goes in line one.
        try:
            _commit = subprocess.run(
                ["git", "rev-parse", "--short", "HEAD"],
                capture_output=True, text=True, timeout=5).stdout.strip()
            _dirty = bool(subprocess.run(
                ["git", "status", "--porcelain"],
                capture_output=True, text=True, timeout=5).stdout.strip())
        except Exception:
            _commit, _dirty = "", False
        with open(args.out, "a", encoding="utf-8") as fh:
            fh.write(json.dumps({
                "kind": "meta", "run": 0,
                "grid": GRID, "algo": args.algo, "braid": args.braid,
                "seed": MAZE_SEED, "goal": list(GOAL),
                "start": list(START), "optimal": optimal,
                # The maze itself, not a recipe for regenerating it. The
                # renderer used to rebuild walls by re-running the carver from
                # the seed, so a later change to a carver or to the RNG would
                # silently draw real routes against invented walls -- and an
                # authored maze has no recipe at all.
                "svg": os.path.basename(args.svg) if args.svg else None,
                "maze": fingerprint,
                "edges": sorted({(min(a, b), max(a, b))
                                 for a, ns in walls.items() for b in ns}),
                "runs": args.runs, "max_steps": args.max_steps,
                "agent": args.agent, "preset": args.preset,
                "ablated": bool(args.ablate_affordances),
                "maze_stats": st, "traps": dec,
                "commit": _commit, "dirty_tree": _dirty,
                "argv": sys.argv[1:],
            }) + "\n")
            fh.flush()
    # One stream for the whole experiment, so run 2 is not a replay of run 1.
    rng = random.Random(20260727)
    rows, turn_base = list(resume.get("rows") or []), int(resume.get("turn_base") or 1)
    if resume.get("rng_state"):
        # Restored so the resumed half of the experiment is not a replay of a
        # stream the first half already consumed.
        s = resume["rng_state"]
        rng.setstate((s[0], tuple(s[1]), s[2]))
    first_run = int(resume.get("run") or 1)
    resume_beat = int(resume.get("beat") or 0)
    resume_route = list(resume.get("visited") or [])

    def _write_checkpoint(run_no, beat, visited):
        if not args.state:
            return
        st_ = rng.getstate()
        tmp = args.state + ".tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            json.dump({"db": db_path, "run": run_no, "beat": beat,
                       "visited": visited, "rows": rows,
                       "turn_base": turn_base, "grid": GRID,
                       "algo": args.algo, "seed": MAZE_SEED,
                       "maze": fingerprint,
                       "rng_state": [st_[0], list(st_[1]), st_[2]]}, fh)
        # Replaced atomically: a checkpoint half-written when the process is
        # killed is worse than none, because it looks resumable.
        os.replace(tmp, args.state)

    for run in range(first_run, args.runs + 1):
        at_resume = (run == first_run and resume_beat > 0)
        if not at_resume:
            reset_position(chat_id, name)
        print(f"\n  run {run}/{args.runs}"
              + (f" (resuming at beat {resume_beat + 1})" if at_resume else ""))
        visited, trace = run_once(
            chat_id, char_id, name, walls, agent=args.agent,
            max_steps=args.max_steps, turn_base=turn_base,
            verbose=args.verbose, rng=rng, show_grid=args.grid,
            optimal_path=shortest_path(walls),
            collect_trace=bool(args.out),
            think_path=args.think, run_no=run,
            resume_from=resume_beat if at_resume else 0,
            resume_visited=resume_route if at_resume else None,
            checkpoint=_write_checkpoint)
        resume_beat, resume_route = 0, []
        turn_base += len(visited)
        m = metrics(visited, optimal)
        rows.append(m)
        if args.out:
            with open(args.out, "a", encoding="utf-8") as fh:
                fh.write(json.dumps(
                    {"run": run, "visited": visited, "trace": trace, **m}) + "\n")
                fh.flush()
        print(f"    beats={m['steps']} moves={m['moves']} "
              f"idle={m['idle_beats']} unique={m['unique']} "
              f"backtracks={m['backtracks']} reversals={m['reversals']} "
              f"reached={m['reached']} excess={m['excess']}")
        # Only between runs. On the last one "set you at the threshold to run
        # it again" would be a lie, and the point of the interlude is that he
        # is not told things that are not so.
        if run < args.runs:
            import db as _db
            _last = _db.q("SELECT id FROM turns WHERE chat_id=? "
                          "ORDER BY idx DESC LIMIT 1", (chat_id,), one=True)
            run_interlude(chat_id, char_id, name, run, m["reached"],
                          _last["id"] if _last else None)

    print("\n" + "=" * 68)
    print(f"{'run':>4} {'beats':>6} {'moves':>6} {'idle':>5} {'unique':>7} "
          f"{'backtrack':>10} {'reversal':>9} {'reached':>8} {'excess':>7}")
    for i, m in enumerate(rows, 1):
        print(f"{i:>4} {m['steps']:>6} {m['moves']:>6} {m['idle_beats']:>5} "
              f"{m['unique']:>7} {m['backtracks']:>10} {m['reversals']:>9} "
              f"{str(m['reached']):>8} "
              f"{'-' if m['excess'] is None else m['excess']:>7}")
    reached = [m for m in rows if m["reached"]]
    print("-" * 68)
    print(f"optimal = {optimal} moves. Reached goal {len(reached)}/{len(rows)}.")
    if len(reached) >= 2:
        first, last = reached[0]["moves"], reached[-1]["moves"]
        print(f"first successful run {first} moves -> last {last} moves "
              f"({'improved' if last < first else 'no improvement'}).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
