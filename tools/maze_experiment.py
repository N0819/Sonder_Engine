#!/usr/bin/env python3
"""Does a character agent get BETTER at a maze it runs repeatedly?

Motivation: NPCs were observed backtracking -- re-entering rooms they had
already been through -- which is the signature of navigating without a usable
spatial memory. This harness isolates that behaviour so it can be measured
instead of eyeballed.

The pipeline is cut down to the four stages that matter for the question:

    character:<id>  ->  director_resolve  ->  perception_outcome  ->  commit

No player, no narrator, no mapping, no loops. `director_interpret` is stubbed
with an empty sequence so the beat is purely the character's own. Everything
that could carry spatial knowledge between runs -- memory, mind models, the
scene blob -- is left exactly as the real engine writes it, because that
carry-over IS the thing under test.

The maze is 6x6, generated by randomised DFS from a fixed seed so every
condition runs the identical layout. Rooms are visually distinct on purpose:
if the character cannot tell two rooms apart, no amount of memory will help,
and we would be measuring the wrong failure.

CONTROL CONDITION. `--agent random` replaces the character stage with a
uniform random choice among legal exits and makes no LLM calls at all. That is
the null hypothesis made runnable: an agent with no memory whatsoever. An LLM
run that does not beat it is not navigating, and an LLM run that does not
IMPROVE across repeats is not learning. Always run the control first -- it is
free, and it validates the harness end to end.

Usage:
    python tools/maze_experiment.py --agent random               # free baseline
    python tools/maze_experiment.py --agent llm --runs 5 --go    # spends tokens

Writes to a scratch DB (--db, default a temp file); never touches engine.db.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

GRID = 6
START = (0, 0)
GOAL = (GRID - 1, GRID - 1)
MAZE_SEED = 20260727

# One distinctive, memorable feature per room. A maze of identical corridors
# tests nothing: the character must be ABLE to tell where they are before we
# can ask whether they remember it.
_FEATURES = [
    "a floor of cracked blue tile", "a rusted iron brazier, long cold",
    "a mural of a running hare", "three broken amphorae in the corner",
    "a low pool of still black water", "a ceiling hung with dry reeds",
    "a toppled stone bench", "walls furred with pale lichen",
    "a doorframe carved with spirals", "a heap of white sand",
    "an upturned bronze bell", "a column split by a root",
    "a floor mosaic of a red fish", "a wall of green glazed brick",
    "a dry fountain shaped like a hand", "scorch marks across the ceiling",
    "a lattice of rotted timber", "a cairn of flat grey stones",
    "a rope ladder to nowhere", "a wall painted with tally marks",
    "a drift of yellow feathers", "a cistern lid, sealed",
    "a bas-relief of two cranes", "an alcove of empty niches",
    "a floor of herringbone brick", "a shattered mirror in a frame",
    "a bundle of iron spikes", "a wall stained with old indigo",
    "a stack of unfired clay tiles", "a low arch of white marble",
    "a chalk circle on the flagstones", "a beam hung with copper wire",
    "a trough of grey ash", "a step worn into a deep hollow",
    "a wall of packed river stones", "a lintel wrapped in faded cord",
]


def _rid(cell):
    return f"r{cell[0]}{cell[1]}"


def build_maze(seed=MAZE_SEED):
    """Randomised-DFS perfect maze. Returns {cell: set(neighbour cells)}."""
    rng = random.Random(seed)
    walls = {(r, c): set() for r in range(GRID) for c in range(GRID)}
    stack, seen = [START], {START}
    while stack:
        r, c = stack[-1]
        nbrs = [
            (r + dr, c + dc) for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1))
            if 0 <= r + dr < GRID and 0 <= c + dc < GRID
            and (r + dr, c + dc) not in seen
        ]
        if not nbrs:
            stack.pop()
            continue
        nxt = rng.choice(nbrs)
        walls[(r, c)].add(nxt)
        walls[nxt].add((r, c))
        seen.add(nxt)
        stack.append(nxt)
    return walls


def shortest_path(walls, a=START, b=GOAL):
    from collections import deque
    prev, queue = {a: None}, deque([a])
    while queue:
        cur = queue.popleft()
        if cur == b:
            break
        for n in walls[cur]:
            if n not in prev:
                prev[n] = cur
                queue.append(n)
    path, cur = [], b
    while cur is not None:
        path.append(cur)
        cur = prev[cur]
    return list(reversed(path))


_DIRS = {(-1, 0): "n", (1, 0): "s", (0, -1): "w", (0, 1): "e"}


def scene_rooms(walls):
    rooms = {}
    for i, (r, c) in enumerate(sorted(walls)):
        cell = (r, c)
        adjacent = []
        for n in sorted(walls[cell]):
            adjacent.append({
                "to": _rid(n), "barrier": "open", "distance": "immediate",
                "dir": _DIRS[(n[0] - r, n[1] - c)],
            })
        feature = _FEATURES[i % len(_FEATURES)]
        rooms[_rid(cell)] = {
            "name": f"Chamber {_rid(cell)[1:]}",
            "desc": f"A square stone chamber with {feature}.",
            "notes": f"Identifying feature: {feature}.",
            "light": "lit",
            "adjacent": adjacent,
        }
    rooms[_rid(GOAL)]["desc"] += (
        " At the centre stands the shrine, unmistakable: a basin of still "
        "water under a shaft of daylight."
    )
    rooms[_rid(GOAL)]["notes"] += " THE SHRINE IS HERE."
    return rooms


# --- the runner --------------------------------------------------------------

def character_sheet(name="Vesk"):
    """Authored so repetition does not extinguish the drive.

    A character asked to do the same thing five times will, correctly, get
    sick of it -- psychology_runtime models exactly that, and a drive that
    strains to rupture would end the experiment early with the character
    refusing, which measures the motivation model rather than navigation. The
    sheet therefore makes repetition the POINT: the goal is not "reach the
    shrine" (satisfied once) but "learn this maze until it can be walked
    without hesitation", which each run advances rather than exhausts.
    """
    from character_schema import default_character_data, normalize_character_data
    sheet = default_character_data(name)
    sheet["identity"]["pronouns"] = {
        "subject": "he", "object": "him", "possessive": "his"}
    sheet["knowledge"] = dict(sheet.get("knowledge") or {})
    sheet["knowledge"]["public_history"] = (
        f"{name} is a pilgrim-cartographer. He has taken a vow to learn the "
        "shrine-maze by heart, and walks it again and again on purpose: each "
        "circuit is a devotion, not a chore. He is patient, methodical, and "
        "takes a quiet satisfaction in recognising a chamber he has seen "
        "before and knowing which way it leads."
    )
    sheet["psychology"] = dict(sheet.get("psychology") or {})
    sheet["psychology"]["traits"] = [
        "methodical", "patient", "quietly stubborn", "attentive to detail",
    ]
    sheet["psychology"]["values"] = [
        "a task finished properly", "knowing a place truly",
    ]
    sheet["initial_state"] = dict(sheet.get("initial_state") or {})
    sheet["initial_state"]["goals"] = [
        "Reach the shrine at the far corner of the maze.",
        "Learn the maze well enough to walk it without hesitation.",
        "Notice and remember what makes each chamber different from the others.",
    ]
    return normalize_character_data(sheet)


def setup(db_path, walls):
    import db
    db.configure(db_path)
    db.init()
    from db import qi, wset
    from character_schema import character_name

    chat_id = qi("INSERT INTO chats(name,scenario,created) VALUES(?,?,?)",
                 ("maze-experiment", "A stone maze with a shrine at its heart.",
                  time.time()))
    sheet = character_sheet()
    char_id = qi(
        "INSERT INTO characters(name,sheet,source,created) VALUES(?,?,?,?)",
        (character_name(sheet), json.dumps(sheet), "{}", time.time()))
    qi("INSERT INTO chat_chars(chat_id,char_id,status,state) VALUES(?,?,'active','{}')",
       (chat_id, char_id))

    wset(chat_id, "scene", {
        "location": "The shrine-maze",
        "time": "morning",
        "rooms": scene_rooms(walls),
        "positions": {character_name(sheet): _rid(START)},
        "entities": {}, "attire": {}, "overlays": {},
        "contacts": [], "contained": {}, "scales": {},
    })
    return chat_id, char_id, character_name(sheet)


def reset_position(chat_id, name):
    from db import wget, wset
    sc = wget(chat_id, "scene", {}) or {}
    sc.setdefault("positions", {})[name] = _rid(START)
    sc.pop("crossings", None)
    wset(chat_id, "scene", sc)


def position_of(chat_id, name):
    from db import wget
    return ((wget(chat_id, "scene", {}) or {}).get("positions") or {}).get(name)


def _random_agent_handler(walls, name, rng):
    """The control: uniform choice among legal exits, no memory, no LLM.

    `rng` is threaded in rather than created here: built per CALL, it reseeded
    every step and produced a deterministic oscillation (56 reversals in 60
    steps, 5 rooms seen) that looked like a pathological walker rather than the
    memoryless one this is supposed to be.
    """
    def handler(ctx, cid, nonce):
        here = position_of(ctx.chat.id, name)
        cell = next(c for c in walls if _rid(c) == here)
        nxt = rng.choice(sorted(walls[cell]))
        return {
            "name": name,
            "sequence": [{
                "type": "action", "verb": "walk",
                "attempt": f"walk into the chamber to the {_DIRS[(nxt[0]-cell[0], nxt[1]-cell[1])]}",
                "observable": "walks to the next chamber",
                "commitment": "uncontested", "targets": [],
                "intended_effects": [], "asserted_effects": [],
            }],
            "_forced_move": _rid(nxt),
        }
    return handler


def run_once(chat_id, char_id, name, walls, *, agent, max_steps, turn_base,
             verbose, rng=None):
    """One traversal. Returns the ordered list of rooms occupied."""
    import db as _db
    from db import qi, wget, wset
    from pipeline_context import PipelineContext, ChatData, TurnData
    from scene import active_cast
    import agents.runtime as runtime

    visited = [position_of(chat_id, name)]
    for step in range(max_steps):
        idx = turn_base + step
        turn_id = qi(
            "INSERT INTO turns(chat_id,idx,player_input,created) VALUES(?,?,?,?)",
            (chat_id, idx, "", time.time()))
        row = _db.q("SELECT * FROM chats WHERE id=?", (chat_id,), one=True)
        ctx = PipelineContext(
            chat=ChatData(id=chat_id, name=row["name"], persona_id=row["persona_id"],
                          lorebook_id=row["lorebook_id"], scenario=row["scenario"],
                          created=row["created"]),
            turn=TurnData(id=turn_id, chat_id=chat_id, idx=idx,
                          player_input="", created=time.time()),
            cast=active_cast(chat_id),
            input="",
        )
        # No player this beat: the sequence is empty and flow asks for nothing.
        ctx["director_interpret"] = {
            "sequence": [], "flow": {"needs_mapping": False, "reactors": [],
                                     "resolution_flags": {}},
            "authorial_offers": [],
        }

        if agent == "random":
            result = _random_agent_handler(walls, name, rng)(ctx, char_id, 0)
            ctx[f"character:{char_id}"] = result
            # The control does not exercise the director; move it directly so
            # the baseline measures NAVIGATION, not the resolver.
            sc = wget(chat_id, "scene", {}) or {}
            sc.setdefault("positions", {})[name] = result["_forced_move"]
            wset(chat_id, "scene", sc)
        else:
            ctx[f"character:{char_id}"] = runtime.compute_step(
                f"character:{char_id}", ctx, 0)
            for key in ("director_resolve", "perception_outcome", "commit"):
                ctx[key] = runtime.compute_step(key, ctx, 0)

        here = position_of(chat_id, name)
        visited.append(here)
        if verbose:
            print(f"    step {step + 1:3}  {here}")
        if here == _rid(GOAL):
            break
    return visited


def metrics(visited, optimal):
    moves = [b for a, b in zip(visited, visited[1:]) if a != b]
    seen, backtracks = set(), 0
    for room in visited:
        if room in seen:
            backtracks += 1
        seen.add(room)
    reversals = sum(
        1 for a, b, c in zip(visited, visited[1:], visited[2:]) if a == c and a != b)
    return {
        "steps": len(visited) - 1,
        "moves": len(moves),
        "unique": len(seen),
        "backtracks": backtracks,
        "reversals": reversals,
        "reached": visited[-1] == _rid(GOAL),
        "optimal": optimal,
        "excess": (len(visited) - 1) - optimal if visited[-1] == _rid(GOAL) else None,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--agent", choices=("random", "llm"), default="random")
    ap.add_argument("--runs", type=int, default=5)
    ap.add_argument("--max-steps", type=int, default=40)
    ap.add_argument("--db", default=None)
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument("--go", action="store_true",
                    help="required for --agent llm; it spends real tokens")
    args = ap.parse_args()

    walls = build_maze()
    optimal = len(shortest_path(walls)) - 1

    if args.agent == "llm" and not args.go:
        calls = args.runs * args.max_steps * 4
        print(f"maze: {GRID}x{GRID}, optimal path {optimal} moves")
        print(f"--agent llm would make UP TO ~{calls} LLM calls "
              f"({args.runs} runs x {args.max_steps} steps x ~4 stages).")
        print("Re-run with --go to spend that. Try --agent random first: it is "
              "free and validates the harness.")
        return 0

    db_path = args.db or tempfile.mkstemp(suffix=".maze.db")[1]
    if os.path.exists(db_path):
        os.remove(db_path)
    print(f"maze {GRID}x{GRID} seed {MAZE_SEED} | optimal {optimal} moves | "
          f"agent={args.agent} | db={db_path}")

    chat_id, char_id, name = setup(db_path, walls)
    # One stream for the whole experiment, so run 2 is not a replay of run 1.
    rng = random.Random(20260727)
    rows, turn_base = [], 1
    for run in range(1, args.runs + 1):
        reset_position(chat_id, name)
        print(f"\n  run {run}/{args.runs}")
        visited = run_once(chat_id, char_id, name, walls, agent=args.agent,
                           max_steps=args.max_steps, turn_base=turn_base,
                           verbose=args.verbose, rng=rng)
        turn_base += len(visited)
        m = metrics(visited, optimal)
        rows.append(m)
        print(f"    steps={m['steps']} unique={m['unique']} "
              f"backtracks={m['backtracks']} reversals={m['reversals']} "
              f"reached={m['reached']} excess={m['excess']}")

    print("\n" + "=" * 68)
    print(f"{'run':>4} {'steps':>6} {'unique':>7} {'backtrack':>10} "
          f"{'reversal':>9} {'reached':>8} {'excess':>7}")
    for i, m in enumerate(rows, 1):
        print(f"{i:>4} {m['steps']:>6} {m['unique']:>7} {m['backtracks']:>10} "
              f"{m['reversals']:>9} {str(m['reached']):>8} "
              f"{'-' if m['excess'] is None else m['excess']:>7}")
    reached = [m for m in rows if m["reached"]]
    print("-" * 68)
    print(f"optimal = {optimal} moves. Reached goal {len(reached)}/{len(rows)}.")
    if len(reached) >= 2:
        first, last = reached[0]["steps"], reached[-1]["steps"]
        print(f"first successful run {first} steps -> last {last} steps "
              f"({'improved' if last < first else 'no improvement'}).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
