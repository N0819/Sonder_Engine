#!/usr/bin/env python3
"""Does a character agent get BETTER at a maze it runs repeatedly?

Motivation: NPCs were observed backtracking -- re-entering rooms they had
already been through -- which is the signature of navigating without a usable
spatial memory. This harness isolates that behaviour so it can be measured
instead of eyeballed.

The pipeline is cut down to the four stages that matter for the question:

    character:<id>  ->  director_resolve  ->  perception_outcome  ->  commit

No player, no narrator, no mapping, no loops. `director_interpret` is stubbed
with an empty sequence so the beat is purely the character's own. Everything
that could carry spatial knowledge between runs -- memory, mind models, the
scene blob -- is left exactly as the real engine writes it, because that
carry-over IS the thing under test.

The maze is 6x6, generated by randomised DFS from a fixed seed so every
condition runs the identical layout. Rooms are visually distinct on purpose:
if the character cannot tell two rooms apart, no amount of memory will help,
and we would be measuring the wrong failure.

`--agent scripted` runs the REAL director/perception/commit chain with only the
model layer stubbed, so the plumbing can be verified for free before any of it
is paid for. It is keyed on the ROLE argument of `_agent_json` (first
positional), not the step name -- getting that wrong silently returns the wrong
agent's output shape, which presents as the character never moving.

CONTROL CONDITION. `--agent random` replaces the character stage with a
uniform random choice among legal exits and makes no LLM calls at all. That is
the null hypothesis made runnable: an agent with no memory whatsoever. An LLM
run that does not beat it is not navigating, and an LLM run that does not
IMPROVE across repeats is not learning. Always run the control first -- it is
free, and it validates the harness end to end.

Usage:
    python tools/maze_experiment.py --agent random               # free baseline
    python tools/maze_experiment.py --agent llm --runs 5 --go    # spends tokens

Writes to a scratch DB (--db, default a temp file); never touches engine.db.
"""

