# Composed so ANY grid size gets a distinct room. The fixed list wrapped with
# `i % len`, so a grid above 6x6 silently reused descriptions -- which destroys
# the one property the experiment depends on, since a character cannot be shown
# to remember a room it cannot tell from another.
_MATERIALS = ("blue tile", "grey slate", "red brick", "white marble",
              "black basalt", "green glaze", "pale sandstone", "cracked plaster")
_FITTINGS = ("a cold brazier", "a toppled bench", "a dry fountain",
             "a rope ladder", "an upturned bell", "a heap of sand",
             "a shattered mirror", "a cairn of stones", "a trough of ash")
_MARKS = ("scored with tally marks", "hung with dry reeds", "streaked with soot",
          "wrapped in faded cord", "dusted with chalk", "bearing a carved spiral",
          "veined with pale lichen", "split by a root")


def _feature_for(index):
    """A distinct feature for ANY room index.

    Three axes, not two. The two-axis version topped out at 108 combinations,
    so a 12x12 (144 rooms) silently reused descriptions -- the same failure the
    fixed 36-entry list had, one grid size further out. This is the property the
    whole experiment rests on: a character cannot be shown to remember a room it
    cannot tell apart from another, so the generator must never run out.
    """
    if index < len(_FEATURES):
        return _FEATURES[index]
    extra = index - len(_FEATURES)
    mat = _MATERIALS[extra % len(_MATERIALS)]
    fit = _FITTINGS[(extra // len(_MATERIALS)) % len(_FITTINGS)]
    mark = _MARKS[(extra // (len(_MATERIALS) * len(_FITTINGS))) % len(_MARKS)]
    return f"a floor of {mat}, {fit} {mark}"


def _rid(cell):
    """Room id. Zero-padded because bare concatenation COLLIDES: at grid 12,
    (1,11) and (11,1) both render "r111", so scene_rooms silently returned 142
    rooms for a 144-cell maze and two pairs of chambers became one. Any grid of
    10 or more was quietly losing rooms."""
    return f"r{cell[0]:02d}{cell[1]:02d}"


def _neighbours(cell, grid):
    r, c = cell
    return [(r + dr, c + dc) for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1))
            if 0 <= r + dr < grid and 0 <= c + dc < grid]


def _carve_kruskal(rng, grid):
    """Randomised Kruskal: a uniform spanning tree.

    DFS carves by walking, which produces long winding corridors and very few
    branch points -- a high "river factor". A 6x6 DFS maze here had THREE
    junctions: a corridor with stubs, navigable by just following it. Kruskal
    picks edges at random across the whole grid instead, so branching is even
    and junctions are many. Same cell count, a far denser decision structure.
    """
    walls = {(r, c): set() for r in range(grid) for c in range(grid)}
    parent = {c: c for c in walls}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    edges = []
    for r in range(grid):
        for c in range(grid):
            if r + 1 < grid:
                edges.append(((r, c), (r + 1, c)))
            if c + 1 < grid:
                edges.append(((r, c), (r, c + 1)))
    rng.shuffle(edges)
    for a, b in edges:
        ra, rb = find(a), find(b)
        if ra == rb:
            continue
        parent[ra] = rb
        walls[a].add(b)
        walls[b].add(a)
    return walls


def _carve_prim(rng, grid):
    """Randomised Prim: grows from one cell, always from the frontier.

    Even shorter corridors than Kruskal and the most dead ends of the three,
    which makes it the most genuinely maze-like: lots of short branches to be
    committed to and back out of.
    """
    walls = {(r, c): set() for r in range(grid) for c in range(grid)}
    seen = {START}
    frontier = [(START, n) for n in _neighbours(START, grid)]
    while frontier:
        i = rng.randrange(len(frontier))
        cur, nxt = frontier.pop(i)
        if nxt in seen:
            continue
        walls[cur].add(nxt)
        walls[nxt].add(cur)
        seen.add(nxt)
        frontier.extend((nxt, n) for n in _neighbours(nxt, grid) if n not in seen)
    return walls


def _carve_dfs(rng, grid):
    walls = {(r, c): set() for r in range(grid) for c in range(grid)}
    stack, seen = [START], {START}
    while stack:
        cur = stack[-1]
        nbrs = [n for n in _neighbours(cur, grid) if n not in seen]
        if not nbrs:
            stack.pop()
            continue
        nxt = rng.choice(nbrs)
        walls[cur].add(nxt)
        walls[nxt].add(cur)
        seen.add(nxt)
        stack.append(nxt)
    return walls


_CARVERS = {"dfs": _carve_dfs, "kruskal": _carve_kruskal, "prim": _carve_prim}


def build_maze(seed=MAZE_SEED, grid=None, braid=0.0, algo="dfs"):
    """Randomised-DFS maze, optionally BRAIDED. {cell: set(neighbour cells)}.

    A perfect maze (braid=0) is a poor instrument for testing whether a
    character LEARNS a space. It has exactly one path between any two cells, so
    there is no better route to discover on run two -- improvement can only
    show as fewer dead-end excursions, and a model that opens on the optimal
    path (grok-4.20 did, exactly) has no headroom at all. It also makes
    backtracking ambiguous: reversing out of a dead end is correct play, and
    the metric cannot tell it from being lost.

    Braiding removes a fraction of dead ends by opening one extra wall each,
    creating LOOPS. That buys three things the perfect maze cannot: genuinely
    competing routes of different length, so route quality becomes measurable;
    unambiguous backtracking, since reversing is now a choice rather than the
    only legal move; and a real navigation decision at junctions instead of a
    corridor to follow.
    """
    grid = grid or GRID
    rng = random.Random(seed)
    walls = _CARVERS[algo](rng, grid)

    if braid > 0:
        dead_ends = [c for c in sorted(walls) if len(walls[c]) == 1]
        rng.shuffle(dead_ends)
        for cell in dead_ends[:int(len(dead_ends) * braid)]:
            if len(walls[cell]) != 1:
                continue  # already opened by an earlier braid
            options = [n for n in _neighbours(cell, grid)
                       if n not in walls[cell]]
            if not options:
                continue
            nxt = rng.choice(options)
            walls[cell].add(nxt)
            walls[nxt].add(cell)
    return walls


def maze_from_svg(path):
    """Parse an orthogonal maze SVG into `(walls, grid, start, goal)`.

    Handles the `<line>`-per-wall form that mazegenerator.net emits. An
    AUTHORED maze buys two things a seeded carver cannot. It can be chosen for
    its shape -- a compact grid with real places to get lost in beats a large
    one that is mostly corridor, and costs a fraction as much to run. And it is
    stable against the harness itself: a seeded maze is only reproducible for
    as long as nobody touches the carver or the Python RNG, whereas the file is
    the maze.

    Start and goal come from the GAPS in the outer border -- the generator's
    entrance and exit -- so the start is wherever the author put it rather than
    always (0, 0). Reading order decides which is which: the opening found
    first scanning top edge, then bottom, then left, then right is the start.
    Exactly two openings are required; anything else is a malformed maze rather
    than something to guess at.
    """
    import re
    src = open(path, encoding="utf-8").read()
    segs = []
    for tag in re.findall(r"<line\b[^>]*>", src):
        try:
            segs.append(tuple(
                float(re.search(r'\b%s="([-0-9.eE+]+)"' % a, tag).group(1))
                for a in ("x1", "y1", "x2", "y2")))
        except AttributeError:
            raise SystemExit(f"{path}: <line> without x1/y1/x2/y2: {tag}")
    if not segs:
        raise SystemExit(f"{path}: no <line> elements -- not a wall-segment "
                         "maze SVG. Path-based or <rect> mazes need a "
                         "different parser.")

    coords = sorted({c for s in segs for c in s})
    off = coords[0]
    steps = sorted({round(b - a, 6) for a, b in zip(coords, coords[1:])
                    if b > a})
    cell = steps[0]
    grid = int(round((coords[-1] - off) / cell))
    if grid < 2:
        raise SystemExit(f"{path}: parsed a {grid}x{grid} grid; the wall "
                         "spacing does not look like a maze.")

    def u(v):
        return int(round((v - off) / cell))

    # Boundary indices, not cell indices: `(j, k)` in `hblock` is the edge
    # above row j in column k, so j runs 0..grid inclusive and j==0 / j==grid
    # are the outer border.
    hblock, vblock = set(), set()
    for x1, y1, x2, y2 in segs:
        if y1 == y2:
            for k in range(u(min(x1, x2)), u(max(x1, x2))):
                hblock.add((u(y1), k))
        elif x1 == x2:
            for k in range(u(min(y1, y2)), u(max(y1, y2))):
                vblock.add((u(x1), k))
        else:
            raise SystemExit(f"{path}: diagonal segment {(x1, y1, x2, y2)}; "
                             "only orthogonal mazes are supported.")

    walls = {(r, c): set() for r in range(grid) for c in range(grid)}
    for r in range(grid):
        for c in range(grid):
            if r + 1 < grid and (r + 1, c) not in hblock:
                walls[(r, c)].add((r + 1, c))
                walls[(r + 1, c)].add((r, c))
            if c + 1 < grid and (c + 1, r) not in vblock:
                walls[(r, c)].add((r, c + 1))
                walls[(r, c + 1)].add((r, c))

    doors = [(0, c) for c in range(grid) if (0, c) not in hblock]
    doors += [(grid - 1, c) for c in range(grid) if (grid, c) not in hblock]
    doors += [(r, 0) for r in range(grid) if (0, r) not in vblock]
    doors += [(r, grid - 1) for r in range(grid) if (grid, r) not in vblock]
    if len(doors) != 2:
        raise SystemExit(
            f"{path}: found {len(doors)} openings in the outer border, "
            f"expected exactly 2 (an entrance and an exit): {doors}. Start and "
            "goal cannot be inferred; add --svg-start/--svg-goal support or "
            "fix the source maze.")
    start, goal = doors
    if start == goal:
        raise SystemExit(f"{path}: entrance and exit are the same room.")

    from collections import deque
    seen, q = {start}, deque([start])
    while q:
        for n in walls[q.popleft()]:
            if n not in seen:
                seen.add(n)
                q.append(n)
    if goal not in seen:
        raise SystemExit(f"{path}: the exit {goal} is walled off from the "
                         f"entrance {start}. The maze is unsolvable.")
    return walls, grid, start, goal


def maze_fingerprint(walls, start, goal):
    """Identity of a maze SHAPE, for refusing to resume across mazes.

    The checkpoint used to be guarded on grid size plus carver name. That was
    only ever a proxy: two runs at the same size and algo but different seeds
    are different mazes, and an authored maze has no algo at all. Hashing the
    open edges compares what actually matters, so route knowledge from one
    layout can never be carried into another.
    """
    import hashlib
    edges = sorted((min(a, b), max(a, b))
                   for a, ns in walls.items() for b in ns)
    edges = sorted(set(edges))
    blob = repr((sorted(walls), edges, start, goal)).encode()
    return hashlib.sha256(blob).hexdigest()[:12]


def deception_stats(walls, start, goal):
    """How much of this maze is a trap, and how deep the traps run.

    Counting dead-end TIPS is the wrong measure of a false path: a one-room
    stub is spotted instantly, while a six-room corridor is a real commitment
    to back out of. What matters is how far off the correct route a wrong turn
    can take you, and how many such branches there are.
    """
    from collections import deque
    prev = {start: None}
    q = deque([start])
    while q:
        cur = q.popleft()
        for n in sorted(walls[cur]):
            if n not in prev:
                prev[n] = cur
                q.append(n)
    path, cur = set(), goal
    while cur is not None:
        path.add(cur)
        cur = prev[cur]
    depth = {c: 0 for c in path}
    q = deque(path)
    while q:
        cur = q.popleft()
        for n in walls[cur]:
            if n not in depth:
                depth[n] = depth[cur] + 1
                q.append(n)
    off = [d for c, d in depth.items() if c not in path]
    tips = [c for c in walls if len(walls[c]) == 1]
    return {
        "off_path": len(off),
        "max_depth": max(off) if off else 0,
        "mean_depth": round(sum(off) / len(off), 1) if off else 0.0,
        "deep_traps": sum(1 for c in tips if depth.get(c, 0) >= 3),
    }


def maze_stats(walls, grid):
    """How much of a navigation problem this actually is."""
    edges = sum(len(v) for v in walls.values()) // 2
    cells = len(walls)
    dead_ends = sum(1 for c in walls if len(walls[c]) == 1)
    junctions = sum(1 for c in walls if len(walls[c]) >= 3)
    # A perfect maze has exactly cells-1 edges; every edge beyond that is a loop.
    return {"cells": cells, "edges": edges, "loops": edges - (cells - 1),
            "dead_ends": dead_ends, "junctions": junctions}


def shortest_path(walls, a=None, b=None):
    """BFS shortest path. `a`/`b` default to the CURRENT module START/GOAL,
    resolved at call time -- binding them as argument defaults froze them to
    the 6x6 goal, so every resized maze reported the distance to (5,5) instead
    of its real corner. A 14x14 was claiming an optimal of 10 moves when its
    Manhattan distance alone is 26."""
    from collections import deque
    a = START if a is None else a
    b = GOAL if b is None else b
    prev, queue = {a: None}, deque([a])
    while queue:
        cur = queue.popleft()
        if cur == b:
            break
        for n in walls[cur]:
            if n not in prev:
                prev[n] = cur
                queue.append(n)
    path, cur = [], b
    while cur is not None:
        path.append(cur)
        cur = prev[cur]
    return list(reversed(path))


_DIRS = {(-1, 0): "n", (1, 0): "s", (0, -1): "w", (0, 1): "e"}


def scene_rooms(walls, goal=None):
    goal = goal or GOAL
    rooms = {}
    for i, (r, c) in enumerate(sorted(walls)):
        cell = (r, c)
        adjacent = []
        for n in sorted(walls[cell]):
            adjacent.append({
                "to": _rid(n), "barrier": "open", "distance": "immediate",
                "dir": _DIRS[(n[0] - r, n[1] - c)],
            })
        feature = _feature_for(i)
        rooms[_rid(cell)] = {
            "name": f"Chamber {_rid(cell)[1:]}",
            "desc": f"A square stone chamber with {feature}.",
            "notes": f"Identifying feature: {feature}.",
            "light": "lit",
            "adjacent": adjacent,
        }
    rooms[_rid(goal)]["desc"] += (
        " At the centre stands the shrine, unmistakable: a basin of still "
        "water under a shaft of daylight."
    )
    rooms[_rid(goal)]["notes"] += " THE SHRINE IS HERE."
    return rooms


